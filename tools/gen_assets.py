def load_drom(path):
    data = open(path, "rb").read()
    if data[0] != 0xE9:
        raise SystemExit("not an ESP32 application image: %s" % path)
    nseg = data[1]
    off = 0x18
    segs = {}
    for _ in range(nseg):
        addr, size = struct.unpack_from("<II", data, off)
        segs[addr] = data[off + 8:off + 8 + size]
        off += 8 + size
        off = (off + 3) & ~3
    if 0x3F400020 not in segs:
        raise SystemExit("image has no DROM segment at 0x3f400020")
    return segs[0x3F400020], data


def c_string(text):
    out = []
    for ch in text:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            for byte in ch.encode("utf-8"):
                out.append("\\x%02x" % byte)
    return '"' + "".join(out) + '"'


def build_bitmaps(drom):
    lines = ["// Generated by tools/gen_assets.py from a local original firmware BIN.",
             "// Recovered OLED assets (see NOTICE.md). Do not redistribute without",
             "// permission from the original author.", "#pragma once",
             "#include <Arduino.h>", ""]
    for name, addr, size in BITMAPS:
        blob = drom[addr - 0x3F400020:addr - 0x3F400020 + size]
        if len(blob) != size:
            raise SystemExit("truncated bitmap read at 0x%08x" % addr)
        lines.append("// %s: 0x%08x, %d bytes" % (name, addr, size))
        lines.append("const uint8_t %s[%d] PROGMEM = {" % (name, size))
        for i in range(0, size, 16):
            row = ", ".join("0x%02x" % b for b in blob[i:i + 16])
            lines.append("  " + row + ",")
        lines.append("};")
        lines.append("")
    return "\n".join(lines) + "\n"


def build_banners(drom):
    def cstr(addr, limit=400):
        raw = drom[addr - 0x3F400020:addr - 0x3F400020 + limit].split(b"\0")[0]
        return raw.decode("utf-8")

    lines = ["// Generated by tools/gen_assets.py from a local original firmware BIN.",
             "// Recovered UI/banner strings (see NOTICE.md).", "#pragma once", ""]
    for name, addr in STRINGS.items():
        lines.append("static const char *%s = %s;" % (name, c_string(cstr(addr))))
    lines.append("")
    for name, addrs in ART.items():
        lines.append("static const char *%s[] = {" % name)
        for addr in addrs:
            lines.append("  " + c_string(cstr(addr)) + ",")
        lines.append("};")
        lines.append("")
    for name, text in MESSAGES.items():
        lines.append("static const char *%s = %s;" % (name, c_string(text)))
    return "\n".join(lines) + "\n"


def default_output_dir(script_dir):
    """Release layout: release/tools/ -> release/source/ESP32-BlueJammer."""
    return os.path.normpath(os.path.join(script_dir, "..", "source", "ESP32-BlueJammer"))


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser()
    ap.add_argument("bin", help="path to a copy of the original application BIN")
    ap.add_argument("--out", default=default_output_dir(script_dir))
    args = ap.parse_args()
    bin_path = args.bin
    if not os.path.isfile(bin_path):
        raise SystemExit(
            "original BIN not found: %s\n"
            "Pass the path to a copy you own: python3 tools/gen_assets.py "
            "<path-to-Official-Combo-Channel_...ino.bin>" % bin_path)
    drom, raw = load_drom(bin_path)
    os.makedirs(args.out, exist_ok=True)
    bitmaps = build_bitmaps(drom)
    banners = build_banners(drom)
    for name, body in (("bitmaps.h", bitmaps), ("banners.h", banners)):
        path = os.path.join(args.out, name)
        open(path, "w").write(body)
        print("%s  %s  sha256=%s" % (name, len(body),
                                     hashlib.sha256(body.encode()).hexdigest()[:16]))
    print("source image sha256=%s" % hashlib.sha256(raw).hexdigest())


if __name__ == "__main__":
    main()
