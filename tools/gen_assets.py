#!/usr/bin/env python3
"""Generate the recovered data headers from a local copy of the original BIN.

The reconstruction embeds UI data that belongs to the original firmware author:
the five monochrome OLED bitmaps and the banner/ASCII-art strings. To keep those
assets out of the distributed source tree, the sketch includes two generated
headers and this script rebuilds them from a BIN the user already owns:

    bitmaps.h  - bitmapboot (128x64) and bitmap1..4 (128x50), byte-exact
    banners.h  - banner rules, ASCII art, UI strings, serial messages

Usage:
    python3 tools/gen_assets.py <path/to/Official-...ino.bin> [--out DIR]

The original BIN is not distributed; pass a path to a copy you own.
Default output: source/ESP32-BlueJammer (this release's sketch directory).
Requires only the Python standard library.
"""
